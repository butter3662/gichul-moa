def _norm(s):
    s = "".join(" " if 0xE000 <= ord(c) <= 0xF8FF else c for c in (s or ""))
    return re.sub(r"\s+", "", s)


def add_also(items, texts):
    """items 를 고쳐 it['also'] 를 넣고 (과목, 단원)별 개수를 돌려준다."""
    cnt = {}
    for it in items:
        it.pop("also", None)
        rules = RULES.get(it.get("subj15"))
        if not rules:
            continue
        q = _norm((texts.get(it["id"]) or {}).get("q"))
        prim = it["subject"] if isinstance(it["subject"], list) else [it["subject"]]
        also = []
        for s, u, rx in rules:
            if s in prim and it.get("unit") == u:
                continue
            if re.search(rx, q) and [s, u] not in also:
                also.append([s, u])
                cnt[(s, u)] = cnt.get((s, u), 0) + 1
        if also:
            it["also"] = also
    return cnt
